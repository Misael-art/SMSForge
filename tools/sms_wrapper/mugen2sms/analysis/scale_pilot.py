    if not args.manifest or not args.out:
        parser.error("--manifest e --out sao obrigatorios fora de --self-check")
    result = audit(args.manifest, args.floor_y, args.video)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n",
                        encoding="utf-8")
    print(f"[MEASURED] scale-pilot status={result['status']} "
          f"idle_peak={result['idle_pair']['metrics']['peak_sprites_per_scanline']}/line "
          f"SAT={result['idle_pair']['metrics']['sat_entries']} "
          f"buffers={result['streaming']['double_buffers_2_fighters_bytes']}/"
          f"{result['streaming']['available_sprite_pattern_vram_bytes']} B "
          f"report={args.out}")
    if args.video:
        fidelity = result["idle_animation_envelope_video_fidelity"]
        print(f"[VIDEO] idle animation envelope/pivot={fidelity['status']} "
              f"frames={fidelity['frames']} report={args.out}")
        if fidelity["status"] != "pass":
            return 1
    return 1 if args.require_measured and result["status"] != "measured" else 0


